import React, { useState } from "react";
import Json from "./components/JsonPane.jsx";

function CopyButton({ text, label = "Copy" }) {
  const [done, setDone] = useState(false);
  const copy = async () => {
    try {
      await navigator.clipboard.writeText(text);
      setDone(true);
      setTimeout(() => setDone(false), 1500);
    } catch { /* no clipboard: the text is selectable */ }
  };
  return <button type="button" className="copy-btn" onClick={copy}>{done ? "Copied" : label}</button>;
}
export { CopyButton };

// The Cedar of every policy the door held during the run, as this lab's mock generates it (a reconstruction of the template's shape).
export function PolicyList({ policies }) {
  if (!policies || policies.length === 0) {
    return <p className="hint" data-testid="no-policies">No policy on the door: nothing can refuse a call except sign-in.</p>;
  }
  return (
    <div className="policy-list" data-testid="policy-list">
      {policies.map((p) => (
        <article key={p.id} className="policy" data-testid={`policy-${p.id}`}>
          <header>
            <strong>{p.id}</strong>
            <span className={`chip state-${p.state.toLowerCase()}`}>{p.state}</span>
            <span className="hint">on {p.tool}, act.sub = {p.agent}</span>
            <CopyButton text={p.cedar} />
          </header>
          <pre className="cedar" data-testid={`cedar-${p.id}`}>{p.cedar}</pre>
        </article>
      ))}
      <p className="hint" data-testid="policy-provenance">
        This Cedar is generated by this lab from the template's shape, with example ids. Only the contains(...) test inside forbid ... unless was
        read from the real tenant on 2026-11-16; the other lines (@reason, the action and resource, the when clause, the has guard) are copied from
        the sibling lab and are UNVERIFIED against the tenant.
      </p>
    </div>
  );
}

export default function RunResult({ result }) {
  if (!result) return null;
  return (
    <div className="run-result" data-testid="run-result">
      <h3>{result.label} <span className="chip">simulated run</span></h3>
      <PolicyList policies={result.policies} />
      {result.kind === "policy-change" ? (
        <p className="hint" data-testid="policy-change-note">
          Policies created as {result.policies.map((p) => p.state).join(" and ")}. The mock only checks the rule shape. From the measured card, not
          from this run: In one run on 2026-11-16 the first poll on the real door, about 7 seconds after the policies were created, already showed
          the refusal. That is one observation, not a measured or guaranteed propagation time. Run step 3 to call the tools.
        </p>
      ) : (
        <div className="call-list" data-testid="call-list">
          {result.calls.map((c) => (
            <div key={c.tool} className={`call ${c.ok ? "ok" : "refused"}`} data-testid={`call-${c.tool}`}>
              <strong>{c.tool}</strong>{" "}
              <span className={`chip verdict-${c.verdict}`} data-testid={`verdict-${c.tool}`}>{c.verdict.toUpperCase()}</span>{" "}
              <span className="hint">HTTP {c.http}</span>
              <p className="run-reason" data-testid={`reason-${c.tool}`}>{c.reason}</p>
            </div>
          ))}
        </div>
      )}
      {result.token ? (
        <details open>
          <summary>Mock token and its claims</summary>
          <p className="hint" data-testid="mock-token-label">
            <span className="chip basis-unmeasured">mock-issued</span> Issued by this lab's in-process PingFederate stand-in (HS256 fixture key);
            it signs nothing real. <CopyButton text={result.token.token} />
          </p>
          <Json value={result.token.token} label="Mock token" testId="mock-token" />
          <Json value={result.token.claims} label="Token claims (mock)" testId="token-claims" hot={["act", "sub", "mock"]} />
        </details>
      ) : (
        <p className="hint" data-testid="no-token">This run sends no token.</p>
      )}
      {result.traceparent && (
        <p className="hint" data-testid="run-traceparent">W3C traceparent of this run: <code>{result.traceparent}</code> (the page sent one; the server continued its trace)</p>
      )}
    </div>
  );
}
